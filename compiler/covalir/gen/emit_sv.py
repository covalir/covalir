"""End-to-end Python -> SystemVerilog Transformer compiler and artifact emitter."""

from __future__ import annotations

import hashlib
import json
import pathlib
from typing import Sequence

from covalir.quant.golden_sim import GoldenTransformerSim, StepTrace
from covalir.quant.quantize_model import QuantMatrix, QuantModel


def _hex_u16(val: int) -> str:
    return f"{val & 0xFFFF:04x}"


def _pack_beat(vals: Sequence[int], quant_mode: str) -> int:
    acc = 0
    if quant_mode == "w4a8":
        for k, v in enumerate(vals):
            acc |= (v & 0xF) << (k * 4)
    elif quant_mode == "ternary":
        for k, v in enumerate(vals):
            code = 1 if v > 0 else (3 if v < 0 else 0)
            acc |= code << (k * 2)
    else:
        raise ValueError(f"Unsupported quant_mode: {quant_mode}")
    return acc


def _emit_matrix_beats(mat: QuantMatrix, lanes: int, quant_mode: str) -> list[str]:
    if mat.cols % lanes != 0:
        raise ValueError(f"Matrix cols ({mat.cols}) must be a multiple of lanes ({lanes})")
    wbits = 2 if quant_mode == "ternary" else 4
    hex_w = (lanes * wbits + 3) // 4
    out: list[str] = []
    for row in mat.weights:
        for b in range(0, mat.cols, lanes):
            packed = _pack_beat(row[b : b + lanes], quant_mode)
            out.append(f"{packed:0{hex_w}x}")
    return out


def _emit_matrix_group_scales(mat: QuantMatrix) -> list[str]:
    return [_hex_u16(s) for row in mat.group_scales for s in row]


def _sha256_file(path: pathlib.Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def emit_compiled_model(
    qmodel: QuantModel,
    out_dir: pathlib.Path,
    lanes: int = 16,
    prompt_tokens: Sequence[int] = (1, 2, 3),
    gen_steps: int = 4,
) -> dict[str, object]:
    """Emit hex images, top-level SV wrapper, Verilator TB, and Yosys synth script."""
    cfg = qmodel.config
    gs = qmodel.group_size
    if gs < lanes or gs % lanes != 0 or cfg.dim % gs != 0 or cfg.hidden_dim % gs != 0:
        raise ValueError(
            f"Invalid geometry: lanes={lanes}, group_size={gs}, dim={cfg.dim}, hidden_dim={cfg.hidden_dim}"
        )

    out_dir = out_dir.resolve()
    mem_dir = out_dir / "mem"
    mem_dir.mkdir(parents=True, exist_ok=True)

    # 1. Run bit-exact GoldenTransformerSim to obtain verified prompt + decode trace
    sim = GoldenTransformerSim(qmodel)
    traces: list[StepTrace] = sim.generate(prompt_tokens, gen_steps=gen_steps)

    # 2. Emit all Q8.8 & per-group hex memory images
    emb_lines = [_hex_u16(v) for row in qmodel.token_embedding for v in row]
    (mem_dir / "emb.hex").write_text("\n".join(emb_lines) + "\n", encoding="utf-8")

    rms_lines: list[str] = []
    for ly in qmodel.layers:
        rms_lines.extend(_hex_u16(v) for v in ly.rms_att)
        rms_lines.extend(_hex_u16(v) for v in ly.rms_ffn)
    rms_lines.extend(_hex_u16(v) for v in qmodel.rms_final)
    (mem_dir / "rms.hex").write_text("\n".join(rms_lines) + "\n", encoding="utf-8")

    w_lines: list[str] = []
    s_lines: list[str] = []
    for ly in qmodel.layers:
        for mat in (ly.wq, ly.wk, ly.wv, ly.wo, ly.w1, ly.w3, ly.w2):
            w_lines.extend(_emit_matrix_beats(mat, lanes, qmodel.quant_mode))
            s_lines.extend(_emit_matrix_group_scales(mat))
    w_lines.extend(_emit_matrix_beats(qmodel.wcls, lanes, qmodel.quant_mode))
    s_lines.extend(_emit_matrix_group_scales(qmodel.wcls))
    (mem_dir / "weights.hex").write_text("\n".join(w_lines) + "\n", encoding="utf-8")
    (mem_dir / "scales.hex").write_text("\n".join(s_lines) + "\n", encoding="utf-8")

    luts = qmodel.luts
    (mem_dir / "inv_rms.hex").write_text(
        "\n".join(_hex_u16(v) for v in luts.inv_rms_lut) + "\n", encoding="utf-8"
    )
    (mem_dir / "silu.hex").write_text(
        "\n".join(_hex_u16(v) for v in luts.silu_lut) + "\n", encoding="utf-8"
    )
    (mem_dir / "exp.hex").write_text(
        "\n".join(f"{v & 0xFF:02x}" for v in luts.exp_lut) + "\n", encoding="utf-8"
    )
    (mem_dir / "rope_cos.hex").write_text(
        "\n".join(_hex_u16(v) for v in luts.rope_cos) + "\n", encoding="utf-8"
    )
    (mem_dir / "rope_sin.hex").write_text(
        "\n".join(_hex_u16(v) for v in luts.rope_sin) + "\n", encoding="utf-8"
    )

    # Emit golden trace file consumed by Verilator testbench
    trace_lines = ["# token_in pos expected_next_token expected_max_logit_s48"]
    for tr in traces:
        trace_lines.append(f"{tr.token_in} {tr.pos} {tr.next_token} {tr.max_logit}")
    (out_dir / "golden_trace.txt").write_text("\n".join(trace_lines) + "\n", encoding="utf-8")

    # 3. Emit model-specialized top-level SystemVerilog wrapper
    use_ternary_bit = "1'b1" if qmodel.quant_mode == "ternary" else "1'b0"
    top_sv = f"""// Auto-generated by CovalIR Phase 1 Compiler (compiler/covalir/gen/emit_sv.py)
// Model: dim={cfg.dim}, hidden_dim={cfg.hidden_dim}, n_layers={cfg.n_layers}, n_heads={cfg.n_heads},
//        vocab_size={cfg.vocab_size}, max_seq_len={cfg.max_seq_len}, quant={qmodel.quant_mode},
//        lanes={lanes}, group_size={gs}

module covalir_top (
  input  logic               clk_i,
  input  logic               rst_ni,
  input  logic               start_i,
  input  logic [15:0]        token_id_i,
  input  logic [15:0]        pos_i,
  output logic               busy_o,
  output logic               done_o,
  output logic [15:0]        next_token_o,
  output logic signed [47:0] max_logit_o
);

  covalir_llm_core #(
    .Dim         ({cfg.dim}),
    .HiddenDim   ({cfg.hidden_dim}),
    .NLayers     ({cfg.n_layers}),
    .NHeads      ({cfg.n_heads}),
    .VocabSize   ({cfg.vocab_size}),
    .MaxSeqLen   ({cfg.max_seq_len}),
    .Lanes       ({lanes}),
    .GroupSize   ({gs}),
    .UseTernary  ({use_ternary_bit}),
    .InvDimQ16   ({luts.inv_dim_q16}),
    .AttScaleQ12 ({luts.att_scale_q12}),
    .EmbHex      ("{(mem_dir / 'emb.hex').as_posix()}"),
    .RmsHex      ("{(mem_dir / 'rms.hex').as_posix()}"),
    .WeightHex   ("{(mem_dir / 'weights.hex').as_posix()}"),
    .ScaleHex    ("{(mem_dir / 'scales.hex').as_posix()}"),
    .InvRmsHex   ("{(mem_dir / 'inv_rms.hex').as_posix()}"),
    .SiluHex     ("{(mem_dir / 'silu.hex').as_posix()}"),
    .ExpHex      ("{(mem_dir / 'exp.hex').as_posix()}"),
    .RopeCosHex  ("{(mem_dir / 'rope_cos.hex').as_posix()}"),
    .RopeSinHex  ("{(mem_dir / 'rope_sin.hex').as_posix()}")
  ) u_core (
    .clk_i        (clk_i),
    .rst_ni       (rst_ni),
    .start_i      (start_i),
    .token_id_i   (token_id_i),
    .pos_i        (pos_i),
    .busy_o       (busy_o),
    .done_o       (done_o),
    .next_token_o (next_token_o),
    .max_logit_o  (max_logit_o)
  );

endmodule
"""
    (out_dir / "covalir_top.sv").write_text(top_sv, encoding="utf-8")

    # 4. Emit Verilator C++ end-to-end differential harness
    tb_cpp = """// Auto-generated CovalIR end-to-end differential Verilator testbench
#include "Vcovalir_top.h"
#include "verilated.h"

#include <cstdint>
#include <fstream>
#include <iostream>
#include <sstream>
#include <string>
#include <vector>

struct Step {
  uint16_t tok_in;
  uint16_t pos;
  uint16_t exp_tok;
  int64_t exp_logit;
};

static int64_t sext48(uint64_t v) {
  v &= 0x0000FFFFFFFFFFFFULL;
  if (v & 0x0000800000000000ULL) {
    return static_cast<int64_t>(v | 0xFFFF000000000000ULL);
  }
  return static_cast<int64_t>(v);
}

static void tick(Vcovalir_top& dut) {
  dut.clk_i = 0;
  dut.eval();
  dut.clk_i = 1;
  dut.eval();
}

int main(int argc, char** argv) {
  Verilated::commandArgs(argc, argv);
  std::string trace_path;
  for (int i = 1; i < argc; ++i) {
    if (std::string(argv[i]) == "--trace" && i + 1 < argc) {
      trace_path = argv[++i];
    }
  }
  if (trace_path.empty()) {
    std::cerr << "Usage: sim_covalir_top --trace <golden_trace.txt>\\n";
    return 2;
  }

  std::ifstream ifs(trace_path);
  std::vector<Step> steps;
  std::string line;
  while (std::getline(ifs, line)) {
    if (line.empty() || line[0] == '#') continue;
    std::istringstream ss(line);
    unsigned ti = 0, p = 0, et = 0;
    int64_t el = 0;
    ss >> ti >> p >> et >> el;
    steps.push_back({static_cast<uint16_t>(ti), static_cast<uint16_t>(p),
                     static_cast<uint16_t>(et), el});
  }

  Vcovalir_top dut;
  dut.rst_ni = 0;
  dut.start_i = 0;
  dut.token_id_i = 0;
  dut.pos_i = 0;
  for (int i = 0; i < 4; ++i) tick(dut);
  dut.rst_ni = 1;
  dut.eval();

  uint64_t total_cycles = 0;
  for (size_t s = 0; s < steps.size(); ++s) {
    dut.token_id_i = steps[s].tok_in;
    dut.pos_i = steps[s].pos;
    dut.start_i = 1;
    tick(dut);
    dut.start_i = 0;

    uint64_t step_cycles = 1;
    bool finished = false;
    while (step_cycles < 500000000ULL) {
      if (dut.done_o) {
        finished = true;
        break;
      }
      tick(dut);
      ++step_cycles;
    }
    if (!finished) {
      std::cerr << "FAIL [covalir_top]: timeout on step " << s << "\\n";
      return 1;
    }
    uint16_t got_tok = static_cast<uint16_t>(dut.next_token_o);
    int64_t got_logit = sext48(static_cast<uint64_t>(dut.max_logit_o));
    if (got_tok != steps[s].exp_tok || got_logit != steps[s].exp_logit) {
      std::cerr << "FAIL [covalir_top] step " << s << " (pos=" << steps[s].pos
                << " tok_in=" << steps[s].tok_in << "): got (tok=" << got_tok
                << ", logit=" << got_logit << ") expected (tok=" << steps[s].exp_tok
                << ", logit=" << steps[s].exp_logit << ")\\n";
      return 1;
    }
    total_cycles += step_cycles;
    tick(dut);
  }

  std::cout << "PASS [covalir_top]: verified " << steps.size()
            << " end-to-end Transformer token steps 100% bit-exact vs golden_sim.py in "
            << total_cycles << " cycles (avg " << (total_cycles / steps.size())
            << " cycles/token).\\n";
  return 0;
}
"""
    (out_dir / "tb_covalir_top.cpp").write_text(tb_cpp, encoding="utf-8")

    # 5. Emit open-source Yosys synthesis script
    repo_root = pathlib.Path(__file__).resolve().parents[3]
    rtl_files = [
        repo_root / "hw/ip/prim/rtl/prim_fifo_sync.sv",
        repo_root / "hw/ip/mac_w4a8/rtl/mac_w4a8.sv",
        repo_root / "hw/ip/mac_ternary/rtl/mac_ternary.sv",
        repo_root / "hw/ip/transformer_core/rtl/covalir_llm_core.sv",
        out_dir / "covalir_top.sv",
    ]
    read_cmds = "\n".join(f"read_verilog -sv {p.as_posix()}" for p in rtl_files)
    yosys_ys = f"""# Auto-generated Yosys synthesis script for CovalIR
{read_cmds}
hierarchy -check -top covalir_top
synth -top covalir_top
stat
"""
    (out_dir / "synth_yosys.ys").write_text(yosys_ys, encoding="utf-8")

    manifest = {
        "config": {
            "dim": cfg.dim,
            "hidden_dim": cfg.hidden_dim,
            "n_layers": cfg.n_layers,
            "n_heads": cfg.n_heads,
            "vocab_size": cfg.vocab_size,
            "max_seq_len": cfg.max_seq_len,
        },
        "quant_mode": qmodel.quant_mode,
        "lanes": lanes,
        "group_size": gs,
        "total_weight_beats": len(w_lines),
        "total_group_scales": len(s_lines),
        "prompt_tokens": list(prompt_tokens),
        "generated_tokens": [tr.next_token for tr in traces],
        "sha256": {
            "covalir_top.sv": _sha256_file(out_dir / "covalir_top.sv"),
            "weights.hex": _sha256_file(mem_dir / "weights.hex"),
            "scales.hex": _sha256_file(mem_dir / "scales.hex"),
            "golden_trace.txt": _sha256_file(out_dir / "golden_trace.txt"),
        },
    }
    (out_dir / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    return manifest
